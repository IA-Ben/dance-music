/* ===================================================================
   FROM THE FLOOR — published first-hand accounts by people in the crowd.
   Each is credited and linked, retold in the book's own words, with at
   most one short quotation from its source. window.FLOOR comes from
   the researchers' files (see build/floor_build.py).
   =================================================================== */
window.Floor = {
  esc: s => String(s == null ? '' : s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c])),
  all() { return window.FLOOR || []; },
  card(s, withPlace) {
    const e = this.esc;
    return `<div class="floor-card"><h4>${e(s.title)}</h4><p class="floor-who">${e(s.who)}${s.when ? ' · ' + e(s.when) : ''}${withPlace !== false && s.where ? ' · ' + e(s.where) : ''}</p><p>${e(s.story)}</p>${s.quote ? `<blockquote>“${e(s.quote)}”</blockquote>` : ''}<p class="cap">${s.source_url ? `<a href="${e(s.source_url)}" target="_blank" rel="noopener">${e(s.source_title || 'Source')}</a>` : e(s.source_title || '')}${s.kind ? ' · ' + e(s.kind) : ''}</p></div>`;
  },
  year(s) { const m = String(s.when || '').match(/(19|20)\d\d/); return m ? +m[0] : null; },
  mount(pageEl, id, isNode) {
    pageEl.querySelectorAll('.floorstrip').forEach(x => x.remove());
    let list = [], title = '';
    if (isNode && typeof NODE !== 'undefined' && NODE[id]) { const names = [NODE[id].title, ...(NODE[id].aliases || [])].map(x => String(x).toLowerCase()); list = this.all().filter(s => (s.pages || []).some(p => names.includes(String(p).toLowerCase()))); title = 'From the floor'; }
    else if (/^y\d{4}$/.test(id)) { const y = +id.slice(1); list = this.all().filter(s => this.year(s) === y); title = `From the floor, ${y}`; }
    if (!list.length) return;
    const d = document.createElement('div'); d.className = 'floorstrip card';
    d.innerHTML = `<h3>${title}</h3><p class="cap">What it was like in the crowd, from published accounts. Each is retold in the book's words; follow the link for the original.</p>${list.slice(0, 6).map(s => this.card(s, !isNode)).join('')}${list.length > 6 ? `<p class="cap"><a class="xl" href="#floor">${list.length - 6} more on the From the floor page →</a></p>` : `<p class="cap"><a class="xl" href="#floor">More stories from the crowd →</a></p>`}`;
    const nav = pageEl.querySelector('.lsstrip') || pageEl.querySelector('.margin-note') || pageEl.querySelector('.pagenav');
    if (nav) pageEl.insertBefore(d, nav); else pageEl.appendChild(d);
    if (window.autolink) try { autolink(d, null); } catch (e) {}
  },
  index() {
    const box = document.getElementById('floorIndex'); if (!box || box.dataset.done) return; box.dataset.done = 1;
    const S = [...this.all()].sort((a, b) => (this.year(a) || 0) - (this.year(b) || 0));
    const decs = [...new Set(S.map(s => this.year(s)).filter(Boolean).map(y => Math.floor(y / 10) * 10))];
    box.innerHTML = `<div class="floor-filters">${['All', ...decs].map(d => `<button type="button" class="chip pt-dec${d === 'All' ? ' on' : ''}" data-d="${d}">${d === 'All' ? 'All ' + S.length : d + 's'}</button>`).join('')}</div><div class="floor-index">${S.map(s => `<div class="floor-item" data-d="${Math.floor((this.year(s) || 0) / 10) * 10}">${this.card(s, true)}</div>`).join('')}</div>`;
    box.querySelectorAll('.pt-dec').forEach(b => b.addEventListener('click', () => { box.querySelectorAll('.pt-dec').forEach(x => x.classList.toggle('on', x === b)); box.querySelectorAll('.floor-item').forEach(it => it.hidden = b.dataset.d !== 'All' && it.dataset.d !== b.dataset.d); }));
    if (window.autolink) try { autolink(box, null); } catch (e) {}
  }
};
